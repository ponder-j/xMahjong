const { chromium } = require('playwright');
const fs = require('fs');
(async () => {
 const browser = await chromium.launch({channel:'msedge',headless:true});
 const page = await browser.newPage({ viewport: {width:1512,height:1100} });
 const errors=[]; page.on('pageerror', e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765');
 await page.getByRole('button',{name:'体验真实示例牌谱'}).click();
 await page.getByRole('button',{name:'分析当前局面', exact:true}).waitFor({state:'visible'});
 await page.waitForFunction(()=> !document.getElementById('analyze').disabled);
 await page.getByRole('button',{name:'分析当前局面', exact:true}).click();
 await page.waitForFunction(()=>document.querySelectorAll('tr[data-candidate]').length>0,{timeout:120000});
 const candidateCount=await page.locator('tr[data-candidate]').count();
 if(candidateCount<2) throw new Error('Missing candidates');
 await page.locator('tr[data-candidate]').nth(1).click();
 await page.getByRole('button',{name:'检验这张弃牌的即时证据'}).click();
 await page.locator('#counterfactual-result:not(.hidden)').waitFor();
 fs.mkdirSync('artifacts',{recursive:true});
 await page.getByRole('button',{name:'下一决策',exact:true}).click();
 await page.waitForFunction(()=>document.getElementById('turn-label').textContent.includes('2'));
 await page.getByRole('button',{name:'连接设置',exact:true}).click();
 await page.getByRole('button',{name:'测试连接',exact:true}).click();
 await page.waitForFunction(()=>document.getElementById('settings-status').textContent.includes('连接成功'));
 await page.getByRole('button',{name:'关闭',exact:true}).click();
 await page.locator('.decision').nth(8).click();
 await page.waitForFunction(()=> !document.getElementById('analyze').disabled);
 await page.getByRole('button',{name:'分析当前局面',exact:true}).click();
 await page.waitForFunction(()=>document.querySelectorAll('tr[data-candidate]').length>0,{timeout:120000});
 await page.screenshot({path:'artifacts/review-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'artifacts/review-mobile.png',fullPage:true});
 const width=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,viewport:innerWidth}));
 if(width.scroll>width.viewport+1) throw new Error('Mobile overflow '+JSON.stringify(width));
 if(errors.length) throw new Error(errors.join('\n'));
 console.log(JSON.stringify({passed:true,candidates:candidateCount,consoleErrors:errors,mobile:width}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
